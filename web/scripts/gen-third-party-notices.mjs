// Writes ../THIRD_PARTY_NOTICES.md from the production dependency tree.
// Run:  cd web && node scripts/gen-third-party-notices.mjs
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = JSON.parse(execSync('pnpm licenses list --prod --json', { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));

let md = `# Third-party notices

notlinear's own code is under the licence in [LICENSE](LICENSE). It depends on the open-source packages
below; each remains under its own licence and copyright. This file is generated by
\`web/scripts/gen-third-party-notices.mjs\` from the production dependency tree.

Notes:
- **MPL-2.0** (BlockNote): file-level copyleft. notlinear uses the packages unmodified; any modified BlockNote
  file must be published under MPL-2.0.
- **EPL-2.0** (elkjs, pulled in by mermaid) and **MPL-2.0 OR Apache-2.0** (dompurify): used unmodified.
- Fonts and icons are not bundled but are loaded at runtime from CDNs (see the last section).
`;
for (const license of Object.keys(out).sort()) {
  const pkgs = out[license].flatMap(p => (p.versions?.length ? p.versions : ['']).map(v => ({ name: p.name, version: v, author: p.author })));
  md += `\n## ${license} (${pkgs.length})\n\n`;
  for (const p of pkgs.sort((a, b) => a.name.localeCompare(b.name))) md += `- ${p.name}${p.version ? ' ' + p.version : ''}${p.author ? ' — ' + String(p.author).replace(/\s+/g, ' ') : ''}\n`;
}
md += `
## Loaded at runtime from CDNs (not bundled)

- Space Grotesk and Space Mono — SIL Open Font License 1.1, via Google Fonts
- Tabler Icons webfont 3.0.0 — MIT, via jsDelivr
- pdf.js (pdfjs-dist) — Apache-2.0, via jsDelivr, only when a PDF is attached
`;
writeFileSync(resolve(here, '../../THIRD_PARTY_NOTICES.md'), md);
console.log('wrote THIRD_PARTY_NOTICES.md');
