// Generates the two files the changelog viewer needs from their legacy sources,
// so prompt-like copy and hand-drawn SVG are never retyped:
//
//   src/changelog/fallback-changelog.ts  <- FALLBACK_CHANGELOG_MD in frontend/app.js
//   src/changelog/story-icons.ts         <- 7 icons in web/public/mind-garden-icons.html
//
// tests/changelog/generated-assets.test.ts re-derives both and fails on drift.
// Run:  cd web && node scripts/gen-changelog-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
export const ICON_IDS = ['branch', 'balance', 'roots', 'hummingbird', 'star', 'compass', 'acorn'];

export function extractFallbackChangelog(appJs) {
  const start = appJs.indexOf('const FALLBACK_CHANGELOG_MD = [');
  if (start < 0) throw new Error('FALLBACK_CHANGELOG_MD not found in app.js');
  const end = appJs.indexOf("].join('\\n');", start);
  if (end < 0) throw new Error('end of FALLBACK_CHANGELOG_MD not found');
  const literal = appJs.slice(start + 'const FALLBACK_CHANGELOG_MD = '.length, end + 1);
  return new Function(`return ${literal}.join('\\n');`)();
}

export function extractIcons(html, ids = ICON_IDS) {
  const doc = new JSDOM(html).window.document;
  const found = {};
  doc.querySelectorAll('figure').forEach(fig => {
    const fc = fig.querySelector('figcaption');
    const code = fc?.querySelector('code')?.textContent?.trim() || '';
    const g = fig.querySelector('svg > g');
    if (!code || !g) return;
    const id = code.replace(/Icon$/, '').replace(/^./, c => c.toLowerCase());
    if (ids.includes(id)) found[id] = g.innerHTML;
  });
  const missing = ids.filter(i => !(i in found));
  if (missing.length) throw new Error(`icons missing from the sheet: ${missing.join(', ')}`);
  return Object.fromEntries(ids.map(i => [i, found[i]]));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const md = extractFallbackChangelog(readFileSync(resolve(root, 'frontend/app.js'), 'utf8'));
  writeFileSync(resolve(here, '../src/changelog/fallback-changelog.ts'),
    `// GENERATED by scripts/gen-changelog-assets.mjs from FALLBACK_CHANGELOG_MD in frontend/app.js.\n` +
    `// Do not edit. Used only when /CHANGELOG.md cannot be fetched (BUGS.md #007).\n\n` +
    `export const FALLBACK_CHANGELOG_MD: string = ${JSON.stringify(md)};\n`);
  const icons = extractIcons(readFileSync(resolve(root, 'web/public/mind-garden-icons.html'), 'utf8'));
  writeFileSync(resolve(here, '../src/changelog/story-icons.ts'),
    `// GENERATED by scripts/gen-changelog-assets.mjs from web/public/mind-garden-icons.html.\n` +
    `// Do not edit. Inner markup of each icon's <svg><g>, trusted repo content rendered as-is.\n\n` +
    `export const STORY_ICON_BODIES: Record<string, string> = ${JSON.stringify(icons, null, 2)};\n`);
  console.log(`fallback: ${md.length} chars; icons: ${Object.keys(icons).join(', ')}`);
}
